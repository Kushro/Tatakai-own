// tokens.json + computed schemes -> tokens.css (custom properties consumed by tk-ui / Dioxus)
import { ROLES, MODES, CONTRAST_LEVELS } from './colors.mjs';
import { springToCss } from './spring.mjs';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function colorBlock(scheme, mode, indent = '  ') {
  const lines = ROLES.map((role) => `${indent}--md-sys-color-${kebab(role)}: ${scheme[role]};`);
  lines.push(`${indent}color-scheme: ${mode === 'light' ? 'light' : 'dark'};`);
  return lines.join('\n');
}

export function emitCss(tokens, all) {
  const out = [];
  out.push(`/* <auto-generated>
 * Generated by packages/tokens/generate.mjs from packages/tokens/tokens.json. DO NOT EDIT BY HAND.
 * Regenerate with: node packages/tokens/generate.mjs
 *
 * Selectors:  :root[data-palette="<id>"][data-mode="light|dark|amoled"][data-contrast="medium|high"]
 * Without data-contrast the palette's standard contrast applies; with no attributes the default palette (dark) applies.
 * </auto-generated> */
`);

  // non-color tokens
  const root = [];
  root.push(`  --tk-font-display: "${tokens.fonts.display}", system-ui, sans-serif;`);
  root.push(`  --tk-font-text: "${tokens.fonts.text}", system-ui, sans-serif;`);
  root.push(`  --tk-font-mono: "${tokens.fonts.mono}", ui-monospace, monospace;`);
  root.push(`  --tk-tv-type-scale: ${tokens.typography.tvScale};`);
  for (const [role, s] of Object.entries(tokens.typography.roles)) {
    const k = kebab(role);
    root.push(`  --md-sys-typescale-${k}-font: var(--tk-font-${s.font});`);
    root.push(`  --md-sys-typescale-${k}-size: ${s.size}px;`);
    root.push(`  --md-sys-typescale-${k}-line-height: ${s.lineHeight}px;`);
    root.push(`  --md-sys-typescale-${k}-weight: ${s.weight};`);
    root.push(`  --md-sys-typescale-${k}-weight-emphasized: ${s.emphasizedWeight};`);
    root.push(`  --md-sys-typescale-${k}-tracking: ${s.tracking}px;`);
  }
  for (const [name, px] of Object.entries(tokens.shape)) root.push(`  --md-sys-shape-corner-${kebab(name)}: ${px}px;`);
  for (const kind of ['spatial', 'effects']) {
    for (const speed of ['fast', 'default', 'slow']) {
      const { durationMs, easing } = springToCss(tokens.motion[kind][speed]);
      root.push(`  --md-sys-motion-${kind}-${speed}-duration: ${durationMs}ms;`);
      root.push(`  --md-sys-motion-${kind}-${speed}-easing: ${easing};`);
    }
  }
  root.push(`  --tk-space-unit: ${tokens.spacing.unit}px;`);
  for (const n of tokens.spacing.scale) root.push(`  --tk-space-${n}: ${n}px;`);
  tokens.elevation.forEach((n, i) => root.push(`  --tk-elevation-${i}: ${n}px;`));
  for (const [k, v] of Object.entries(tokens.density)) root.push(`  --tk-density-${k}: ${v};`);
  out.push(`:root {\n${root.join('\n')}\n}\n`);

  // default = default palette, dark, standard contrast
  out.push(`:root {\n${colorBlock(all[tokens.defaultPalette].standard.dark, 'dark')}\n}\n`);

  for (const level of CONTRAST_LEVELS) {
    for (const id of Object.keys(tokens.palettes)) {
      for (const mode of MODES) {
        const attr = level === 'standard' ? '' : `[data-contrast="${level}"]`;
        out.push(`:root[data-palette="${id}"][data-mode="${mode}"]${attr} {\n${colorBlock(all[id][level][mode], mode)}\n}\n`);
      }
    }
  }
  return out.join('\n');
}
