#!/usr/bin/env node
// Runs reference-mapper.mjs over the recorded fixtures and writes expected.json (the oracle for Kotlin and Rust tests).
//   node contracts/fixtures/metadata/gen-expected.mjs           write expected.json
//   node contracts/fixtures/metadata/gen-expected.mjs --check   exit 1 if expected.json is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mapAniListPage, mapAniZipEpisodes, mapAniZipIds, mapKitsuMedia, mapKitsuEpisodes } from './reference-mapper.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(here, f), 'utf8'));

export function buildExpected() {
  const kitsuList = read('kitsu-anime-list.json');
  return {
    $comment: 'GENERATED by gen-expected.mjs from the fixtures next to it. Do not edit by hand. Field names are core:model (Kotlin) names.',
    'anilist-trending-page.json': mapAniListPage(read('anilist-trending-page.json')),
    'anilist-search-page.json': mapAniListPage(read('anilist-search-page.json')),
    'anizip-frieren.json': { ids: mapAniZipIds(read('anizip-frieren.json')), episodes: mapAniZipEpisodes(read('anizip-frieren.json')) },
    'kitsu-anime-list.json': { items: kitsuList.data.map((r) => mapKitsuMedia(kitsuList, r)), hasNext: Boolean(kitsuList.links?.next) },
    'kitsu-episodes.json': { episodes: mapKitsuEpisodes(read('kitsu-episodes.json')) },
    'anilist-rate-limited.json': { error: { kind: 'RateLimited', provider: 'anilist', cooldownSeconds: 60 } },
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = JSON.stringify(buildExpected(), null, 2) + '\n';
  const out = join(here, 'expected.json');
  if (process.argv.includes('--check')) {
    const cur = readFileSync(out, 'utf8').replaceAll('\r\n', '\n');
    if (cur !== text) {
      console.error('expected.json is stale: run node contracts/fixtures/metadata/gen-expected.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
