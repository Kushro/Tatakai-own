package app.tatakai.next.extensionserver

import java.net.URI
import java.net.URLDecoder
import java.util.Locale

/** A one-time pairing link of the PC: [server] is an origin that passed [HostGuard], [code] the single-use pairing code. */
data class PairingLink(val server: String, val code: String) {
    /** Never prints the code: it is a one-time secret. */
    override fun toString(): String = "PairingLink(server=$server)"
}

/** Why a scanned / pasted / opened link was rejected. */
sealed interface DeepLinkResult {
    data class Valid(val link: PairingLink) : DeepLinkResult

    /** Not a `tatakai://extensionserver/connect` link, or its `server` / `code` are malformed. */
    data object Invalid : DeepLinkResult

    /** Well-formed, but the server is plain `http:` on a non-local host (docs/redesign/13 §3.8). */
    data class InsecureHost(val host: String) : DeepLinkResult
}

/**
 * Parser of the pairing link generated by the PC (docs/redesign/13 §3.7):
 * `tatakai://extensionserver/connect?server=<encodeURIComponent(origin)>&code=<encodeURIComponent(code)>`.
 * This app accepts only that form (scheme and host are case-insensitive, the path is exactly `/connect`, optionally with a trailing `/`);
 * no web-hosted link is accepted (contracts guard). `server` must be an origin without path; `code` 1..128 chars of `[A-Za-z0-9_-]`.
 */
object DeepLink {
    const val SCHEME = "tatakai"
    const val HOST = "extensionserver"
    const val PATH = "/connect"
    private const val MAX_LINK = 4096
    private val CODE = Regex("[A-Za-z0-9_-]{1,128}")

    fun parse(uri: String): PairingLink? = (parseResult(uri) as? DeepLinkResult.Valid)?.link

    fun parseResult(text: String): DeepLinkResult {
        val trimmed = text.trim()
        if (trimmed.isEmpty() || trimmed.length > MAX_LINK) return DeepLinkResult.Invalid
        val uri = try {
            URI(trimmed)
        } catch (_: Exception) {
            return DeepLinkResult.Invalid
        }
        if (uri.scheme?.lowercase(Locale.ROOT) != SCHEME) return DeepLinkResult.Invalid
        if (uri.host?.lowercase(Locale.ROOT) != HOST || uri.port != -1 || uri.rawUserInfo != null) return DeepLinkResult.Invalid
        val path = uri.rawPath.orEmpty()
        if (path != PATH && path != "$PATH/") return DeepLinkResult.Invalid
        val params = query(uri.rawQuery ?: return DeepLinkResult.Invalid) ?: return DeepLinkResult.Invalid
        val serverRaw = params["server"] ?: return DeepLinkResult.Invalid
        val code = params["code"]?.takeIf { CODE.matches(it) } ?: return DeepLinkResult.Invalid
        val origin = HostGuard.originOf(serverRaw) ?: return DeepLinkResult.Invalid
        // The PC sends `new URL(...).origin`: anything that normalizes differently (path, credentials) was rejected above.
        if (!HostGuard.isAllowed(origin)) {
            val host = runCatching { URI(origin).host }.getOrNull().orEmpty()
            return DeepLinkResult.InsecureHost(host)
        }
        return DeepLinkResult.Valid(PairingLink(origin, code))
    }

    /** Builds the canonical link (tests, sharing). */
    fun build(link: PairingLink): String =
        "$SCHEME://$HOST$PATH?server=${encode(link.server)}&code=${encode(link.code)}"

    /** Decoded query parameters; null when a key repeats or a value does not decode. Unknown keys are ignored. */
    private fun query(raw: String): Map<String, String>? {
        val out = HashMap<String, String>()
        for (part in raw.split('&')) {
            if (part.isEmpty()) continue
            val eq = part.indexOf('=')
            if (eq <= 0) return null
            val key = decode(part.substring(0, eq)) ?: return null
            val value = decode(part.substring(eq + 1)) ?: return null
            if (out.put(key, value) != null) return null
        }
        return out
    }

    private fun decode(s: String): String? = try {
        // encodeURIComponent never emits '+', so a literal '+' must stay a '+' (URLDecoder would turn it into a space).
        URLDecoder.decode(s.replace("+", "%2B"), "UTF-8")
    } catch (_: Exception) {
        null
    }

    private fun encode(s: String): String =
        java.net.URLEncoder.encode(s, "UTF-8").replace("+", "%20")
}
